const char *tr(Language language, TextKey key) {
  if (language < 0 || language >= LANG_COUNT) language = LANG_EN;
  if (key < 0 || key >= T_COUNT) return "";
  return text[language][key] ? text[language][key] : "";
}

const char *language_name(Language language) {
  static const char *const names[] = {"English", "Español", "Català"};
  return names[language >= 0 && language < LANG_COUNT ? language : 0];
}
